#include "Parser.h"
#include "Parser_internal.h"
#include <iostream>

Parser::Parser(std::unordered_set<std::string> initialClassNames, GenericRegistry* sharedRegistry)
    : classNames(std::move(initialClassNames)) {
    if (sharedRegistry) gen_ = sharedRegistry;
}

Program Parser::parse(const std::vector<Token>& inputTokens, const std::string& filenameStr,
                      bool runMono) {
    tokens   = std::vector<Token>(inputTokens);
    current  = 0;
    filename = filenameStr;

    // Module namespacing: read this file's `module`/symbol-imports, register its members (into the
    // possibly-shared registry), then rewrite the token stream so every name carries its module
    // prefix — exactly like generic mangling. Skipped entirely when no module is in play, so a
    // module-less program's tokens (and thus its IR) are byte-identical to before.
    scanModuleDirectives(tokens, currentModule_, importBindings_, ambiguousImports_);
    scanModuleMembers(tokens, currentModule_, gen_->moduleTypes, gen_->moduleFuncs, gen_->moduleNames);
    if (!currentModule_.empty() || !gen_->moduleNames.empty())
        tokens = qualifyTokens(tokens, currentModule_, importBindings_, ambiguousImports_,
                               gen_->moduleTypes, gen_->moduleFuncs, gen_->moduleNames);

    // Register this file's template/class names (idempotent if pre-seeded by the caller).
    prescanTemplateNames(tokens);

    Program program;
    while (!isAtEnd()) {
        // Consume module-namespacing directives (already recorded above); they emit no AST node.
        if (check(TokenType::MODULE)) {                 // `module NAME ('.' NAME)* ;`
            advance();
            if (check(TokenType::IDENTIFIER)) {
                advance();
                while (check(TokenType::DOT) && peekNext().type == TokenType::IDENTIFIER) {
                    advance();   // '.'
                    advance();   // IDENT
                }
            }
            (void)match({ TokenType::SEMICOLON });
            continue;
        }
        if (check(TokenType::IMPORT) && peekNext().type != TokenType::STRING) {   // `import a.B ;`
            while (!isAtEnd() && !check(TokenType::SEMICOLON)) advance();
            (void)match({ TokenType::SEMICOLON });
            continue;
        }
        if (tryCaptureClassTemplate())    continue;   // generic decls produce no AST node
        if (tryCaptureFunctionTemplate()) continue;
        if (tryCaptureImplTemplate())     continue;
        program.declarations.push_back(parseDeclaration());
    }

    // Emit any canonical `Call$…` trait declarations generated by Call bounds / `impl Call` / lambdas
    // (deduped across files via the shared registry) before the concrete decls that reference them.
    for (Stmt& t : pendingCallTraits_) program.declarations.push_back(std::move(t));
    pendingCallTraits_.clear();
    for (Stmt& d : pendingLambdaDecls_) program.declarations.push_back(std::move(d));
    pendingLambdaDecls_.clear();

    if (runMono) runMonomorphization(program);   // expand instantiations now (single-file path)
    return program;
}

// ============================================================
// Token stream navigation
// ============================================================

const Token& Parser::peek() const {
    return tokens[current];
}

const Token& Parser::peekNext() const {
    if (current + 1 >= tokens.size()) return tokens.back();
    return tokens[current + 1];
}

const Token& Parser::previous() const {
    return tokens[current - 1];
}

bool Parser::isAtEnd() const {
    return peek().type == TokenType::END_OF_FILE;
}

const Token& Parser::advance() {
    if (!isAtEnd()) current++;
    return previous();
}

bool Parser::check(TokenType type) const {
    return !isAtEnd() && peek().type == type;
}

bool Parser::match(std::initializer_list<TokenType> types) {
    for (TokenType type : types) {
        if (check(type)) { advance(); return true; }
    }
    return false;
}

const Token& Parser::consume(TokenType type, const std::string& msg) {
    if (check(type)) return advance();
    throw error(peek(), msg);
}

// ============================================================
// Error handling
// ============================================================

void Parser::throwTypeExpected(const std::string& what) {
    const Token& t = peek();
    std::string msg = "expected " + what;
    if (t.type == TokenType::IDENTIFIER) {
        // A bare identifier in type position looks like a type name that isn't declared.
        msg += ", but '" + t.lexeme + "' is not a known type "
               "(expected a primitive, a declared class or enum, or Self)";
        if (inImplBlock_)
            msg += ". Note: an `impl` only sees the type parameters it declares — to use `T`, "
                   "write `impl<T> Trait for Foo<T> { ... }` (declare `T` right after `impl`)";
    } else {
        msg += ", but found '" + t.lexeme + "'";
    }
    throw error(t, msg);
}

ParseError Parser::error(const Token& token, const std::string& msg) {
    std::string prefix = filename.empty() ? "" : filename + ":";
    std::string formatted = prefix + std::to_string(token.line) + ": error: " + msg;
    // Do NOT print here — the thrown ParseError carries the message, and the top-level
    // handler (GG::run / the test helpers) prints it exactly once. Printing here as well
    // duplicated every parse error, and printed speculative errors that were recovered
    // from during template/lambda look-ahead (which catch and discard the exception).
    return ParseError(formatted);
}

void Parser::synchronize() {
    advance();
    while (!isAtEnd()) {
        if (previous().type == TokenType::SEMICOLON) return;
        switch (peek().type) {
            case TokenType::IF:
            case TokenType::WHILE:
            case TokenType::FOR:
            case TokenType::RETURN:
            case TokenType::BREAK:
            case TokenType::CONTINUE:
            case TokenType::IMPORT:
            case TokenType::EXTERN:
            case TokenType::I8:
            case TokenType::I16:
            case TokenType::I32:
            case TokenType::I64:
            case TokenType::U8:
            case TokenType::U16:
            case TokenType::U32:
            case TokenType::U64:
            case TokenType::F32:
            case TokenType::F64:
            case TokenType::BOOL:
            case TokenType::CHAR_TYPE:
            case TokenType::VOID:
            case TokenType::PTR:
                return;
            default:
                break;
        }
        advance();
    }
}

