bool Parser::isTypeName() const {
    switch (peek().type) {
        case TokenType::I8:
        case TokenType::I16:
        case TokenType::I32:
        case TokenType::I64:
        case TokenType::U8:
        case TokenType::U16:
        case TokenType::U32:
        case TokenType::U64:
        case TokenType::F32:
        case TokenType::F64:
        case TokenType::BOOL:
        case TokenType::CHAR_TYPE:
        case TokenType::VOID:
        case TokenType::PTR:
        case TokenType::STR:
            return true;
        case TokenType::SELF:
            return true;   // valid only inside trait/impl bodies; semantic enforces that
        case TokenType::IDENTIFIER:
            return classNames.count(peek().lexeme) > 0 || gen_->classNames.count(peek().lexeme) > 0;
        case TokenType::LEFT_PAREN:
            // A tuple type `(T1, T2, …)` starts with '('. Confirm it is a full, valid tuple-type
            // span (≥ 2 type elements, closing ')') so a grouped expression `(a + b)` or a tuple
            // *literal* `(a, b)` (whose elements are values, not types) is not mistaken for a type.
            return typeSpanAt(current) > 0;
        default:
            return false;
    }
}

// A type with an optional trailing `?` (nullable). `T?` → a synthesized token whose lexeme is the
// core spelling plus `?` (`Class&?`, `ref:Class?`, `Color?`, `i32?`); decodeSynthesizedType /
// resolveTypeToken decode the suffix. Nested `??` is a parse error.
Token Parser::consumeType() {
    Token base = consumeTypeCore();
    if (match({ TokenType::QUESTION })) {
        if (check(TokenType::QUESTION))
            throw error(peek(), "nested '?\?' is not allowed; a nullable type is written 'T?'");
        // The '&'/'*' suffix must come BEFORE '?', never after (`Class&?`/`Class*?`, not
        // `Class?&`/`Class?*`) — there is only one nullability axis for a reference (the handle
        // itself is either null or points at a fully-formed object; there is no separate "valid
        // handle to an absent object" state), so the reversed order is never meaningful and would
        // otherwise fail later with a confusing, unrelated "expected expression".
        if (check(TokenType::AMPERSAND) || check(TokenType::STAR))
            throw error(peek(), "'" + peek().lexeme + "' must come before '?', not after; write '" +
                                     base.lexeme + peek().lexeme + "?' instead of '" + base.lexeme +
                                     "?" + peek().lexeme + "'");
        return Token{ TokenType::IDENTIFIER, base.lexeme + "?", base.line };
    }
    return base;
}

Token Parser::consumeTypeCore() {
    // A tuple type `(T1, T2, …)` yields a synthesized IDENTIFIER token (the `Tuple$…` class name);
    // otherwise the base is the next type token. Either way, the shared `&`/`*` suffix logic below
    // applies (a tuple has no `<…>` args, so those branches are naturally skipped for it) — so a
    // tuple can be borrowed (`(i32,i32)*`) or owned-referenced (`(i32,i32)&`) like any class.
    Token base = check(TokenType::LEFT_PAREN) ? consumeTupleType() : advance();

    std::string lexeme = base.lexeme;
    int         line   = base.line;
    // `Self` (SELF) and class identifiers are the reference-capable ("class-like") types.
    bool        classLike = base.type == TokenType::IDENTIFIER || base.type == TokenType::SELF;

    // Typed raw pointer: ptr<T> -> synthesized "ptr<elem>" token (internal type).
    if (base.type == TokenType::PTR && check(TokenType::LESS)) {
        std::vector<std::vector<Token>> args = parseTypeArgList();
        std::string elem = args.empty() ? "" : argMangle(args[0]);
        return Token{ TokenType::IDENTIFIER, "ptr<" + elem + ">", line };
    }

    // Generic class instantiation: Name<args> -> mangled concrete class name.
    if (base.type == TokenType::IDENTIFIER && gen_->classNames.count(base.lexeme)
        && check(TokenType::LESS)) {
        std::vector<std::vector<Token>> args = parseTypeArgList();
        std::string mangled = mangleInstantiation(base.lexeme, args);
        recordInstantiation(base.lexeme, mangled, std::move(args));
        classNames.insert(mangled);   // the instantiation is now a concrete class name
        lexeme    = mangled;
        classLike = true;
    }

    if (check(TokenType::AMPERSAND)) {
        bool refOk = base.type == TokenType::SELF || (classLike && classNames.count(lexeme) > 0);
        if (!refOk)
            throw error(peek(), "'&' reference type is only allowed on class types, not '" + lexeme + "'");
        advance();  // consume '&'
        // Synthesize a single reference-type token; resolvers decode the trailing '&'.
        return Token{ TokenType::IDENTIFIER, lexeme + "&", line };
    }

    // Borrow: `T*` → synthesized "ref:T" (a non-owning reference). The inner type may be a
    // class/`Self` or a primitive value type (`i32*`, an lvalue reference to the primitive — like
    // C++'s `int&`; `str*` included — `str` is an ordinary `{ptr,i64}` value type with the same
    // addressable-storage story as any other primitive). `ptr`/`void` cannot be borrowed (opaque,
    // no fixed IR representation to take an lvalue reference to). A generic `T*` reaches here only
    // after monomorphization has substituted T with a concrete type token (which may itself be a
    // mangled generic instantiation, e.g. `Vec$i32*`).
    if (check(TokenType::STAR)) {
        bool primitiveInner = isTypeKeyword(base.type)
                              && base.type != TokenType::PTR && base.type != TokenType::VOID;
        if (!(classLike || primitiveInner))
            throw error(peek(), "'*' borrow is only allowed on class types, `Self`, or a primitive "
                                "like `i32`; `ptr` and `void` cannot be borrowed");
        advance();  // consume '*'
        std::string inner = base.type == TokenType::SELF ? "Self" : lexeme;
        return Token{ TokenType::IDENTIFIER, "ref:" + inner, line };
    }

    if (lexeme != base.lexeme)  // a generic instantiation was mangled
        return Token{ TokenType::IDENTIFIER, lexeme, line };
    return base;
}

// A tuple type `(T1, T2, …)` (arity ≥ 2). Each element is a value or primitive type (v1 rejects
// `&`/`*`/`?`/`ptr` elements so the mangled name is a clean identifier). Produces the canonical
// class name `Tuple$<e1>$<e2>…` (each element lexeme is already a clean identifier — a primitive
// keyword, a class name, or a nested `Tuple$…`), records a one-shot synthesis request keyed by that
// name, and returns it as a single synthesized IDENTIFIER token — an ordinary value-object type to
// everything downstream. `consumeType` recursion handles nesting: `((i32,i32), str)` works.
Token Parser::consumeTupleType() {
    Token lparen = advance();   // '('
    int   line   = lparen.line;

    std::vector<Token> elems;
    do {
        if (!isTypeName())
            throw error(peek(), "expected a type in a tuple type '(T1, T2, …)'");
        Token e = consumeType();
        const std::string& lx = e.lexeme;
        bool badSigil = (!lx.empty() && (lx.back() == '&' || lx.back() == '?'))
                     || lx.rfind("ref:", 0) == 0
                     || lx == "ptr" || lx.rfind("ptr<", 0) == 0
                     || lx == "void";
        if (badSigil)
            throw error(e, "tuple elements must be value or primitive types in v1 "
                           "(no '&', '*', '?', or raw pointers); found '" + lx + "'");
        elems.push_back(e);
    } while (match({ TokenType::COMMA }));

    consume(TokenType::RIGHT_PAREN, "expected ')' to close a tuple type");

    if (elems.size() < 2)
        throw error(lparen, "a tuple type needs at least two elements; '(T)' is just grouping "
                            "and '()' is reserved");

    std::string mangled = "Tuple";
    for (const Token& e : elems) mangled += "$" + e.lexeme;

    classNames.insert(mangled);
    gen_->classNames.insert(mangled);
    if (gen_->tupleRequests.find(mangled) == gen_->tupleRequests.end()) {
        std::vector<Token> copy;
        copy.reserve(elems.size());
        for (const Token& e : elems) copy.push_back(e);   // Token copy-ctor is fine (only assign is deleted)
        gen_->tupleRequests.emplace(mangled, std::move(copy));
    }
    return Token{ TokenType::IDENTIFIER, mangled, line };
}

