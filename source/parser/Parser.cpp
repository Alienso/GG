Stmt Parser::parseDeclaration() {
    // A leading `@Name(...)` in declaration position is an annotation applied to the following
    // class. Disambiguated from statement-level reflection builtins (`@compileError`, …) by CASE:
    // annotation types are Capitalized, builtins are lowercase. A lowercase `@…` falls through to
    // parseStatement (an expression statement) below.
    if (check(TokenType::AT) && peekNext().type == TokenType::IDENTIFIER
        && !peekNext().lexeme.empty() && std::isupper(static_cast<unsigned char>(peekNext().lexeme[0]))) {
        std::deque<AnnotationApp> anns = parseAnnotationPrefixes();
        Token where = previous();
        if (match({ TokenType::CLASS })) {
            Stmt s = parseClassDecl();
            std::get<ClassDeclStmt>(*s.node).annotations = std::move(anns);
            return s;
        }
        if (match({ TokenType::ENUM })) {
            Stmt s = parseEnumDecl();
            // enum-level annotations are recorded on… v1 has no enum-type annotation slot beyond
            // variants, so reject to keep the surface honest.
            (void)anns;
            throw error(where, "annotations on an 'enum' type are not supported; annotate its "
                               "variants or fields instead");
        }
        throw error(where, "an annotation here must prefix a 'class' declaration");
    }

    // extern returnType name( params );
    if (match({ TokenType::IMPORT })) {
        Token keyword = previous();
        return parseImportStmt(keyword);
    }

    if (match({ TokenType::EXTERN })) {
        Token keyword = previous();
        return parseExternFuncDecl(keyword);
    }

    if (match({ TokenType::CLASS })) {
        return parseClassDecl();
    }

    if (match({ TokenType::ENUM })) {
        return parseEnumDecl();
    }

    if (match({ TokenType::ANNOTATION })) {
        return parseAnnotationDecl();
    }

    if (match({ TokenType::TRAIT })) {
        return parseTraitDecl();
    }

    if (match({ TokenType::IMPL })) {
        return parseImplDecl();
    }

    // Every function declaration begins with `fn`.
    if (match({ TokenType::FN })) {
        return parseFnDeclaration();
    }
    return parseStatement();
}

void Parser::recordLocal(const Token& typeToken, const Token& name) {
    if (!scopes_.empty()) scopes_.back().emplace(name.lexeme, typeToken);
}

Stmt Parser::parseImportStmt(const Token& keyword) {
    Token path = consume(TokenType::STRING, "expected file path string after 'import'");
    consume(TokenType::SEMICOLON, "expected ';' after import path");
    return makeStmt(ImportStmt{ keyword, path });
}

Stmt Parser::parseStatement() {
    if (check(TokenType::LEFT_BRACE))   return parseBlock();
    if (match({ TokenType::IF     }))   return parseIfStmt();
    if (match({ TokenType::WHILE  }))   return parseWhileStmt();
    if (match({ TokenType::FOR    }))   return parseForStmt();
    if (match({ TokenType::INLINE }))   return parseInlineForStmt();
    if (match({ TokenType::RETURN }))   return parseReturnStmt();
    if (match({ TokenType::BREAK }))    return parseBreakStmt();
    if (match({ TokenType::CONTINUE })) return parseContinueStmt();
    if (match({ TokenType::SWITCH }))   return parseSwitchStmt();
    if (match({ TokenType::MATCH }))    return parseMatchStmt();
    if (match({ TokenType::YIELD }))    return parseYieldStmt();
    return parseExprStmt();
}

BlockStmt Parser::parseBlockBody() {
    // Called after '{' has already been consumed. Opens a lexical scope (for lambda capture
    // analysis), seeded with any pending params from the enclosing function/lambda signature.
    scopes_.emplace_back();
    for (auto& [n, t] : pendingScopeSeed_) scopes_.back().emplace(n, t);
    pendingScopeSeed_.clear();

    std::vector<std::unique_ptr<Stmt>> body;
    while (!check(TokenType::RIGHT_BRACE) && !isAtEnd()) {
        body.push_back(std::make_unique<Stmt>(parseDeclaration()));
    }
    consume(TokenType::RIGHT_BRACE, "expected '}'");
    scopes_.pop_back();
    return BlockStmt{ std::move(body) };
}

Stmt Parser::parseBlock() {
    consume(TokenType::LEFT_BRACE, "expected '{'");
    return makeStmt(parseBlockBody());
}